console.log("Switch It Up");

function Switch_it_up(num){
    switch (num) {
      case 0:
        return "Zero";
      case 1:
        return "one";
      case 2:
        return "two";
      case 3:
        return "three";

      case 4:
        return "four";
      case 5:
        return "five";
      case 6:
        return "six";
      case 7:
        return "seven";

      case 8:
        return "eight";
      case 9:
        return "nine";

      default:
        break;
    }

}

let result = Switch_it_up(3)
console.log(result)